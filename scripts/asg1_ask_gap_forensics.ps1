<#
ASG1 forensic probe (FIX-ASK-SILENT-GAP-1 recon leg; worktree-only, never merge):
decompose the ask->slice-start gap on the live stack.

Measures, from the same chat POST used by the M2 experience session:
  * first arrival of every /agent/events row for this conversation
    (turn.started, trajectory.turn.started, turn.completed/failed/stopped ...)
  * first appearance of slice_1 / turn_1 in /agent/state (task runtime face)
  * optionally POSTs /agent/turn/stop once slice_1 is observed, so the round
    does not burn message-loop LLM budget after the measured boundary.

Method notes copied from f4_turn_started_timing_smoke.ps1 (learned the hard
way): the chat POST goes over a raw TCP socket because HttpWebRequest blocks
until the whole turn answers and destroys the concurrent event polling; the
message text is built from [char] codes because Windows PowerShell 5.1 reads
.BOM-less .ps1 as ANSI and corrupts literal CJK.

This is a forensic probe, not a pass/fail gate: exit 0 = timeline captured.
#>
[CmdletBinding()]
param(
    [string]$AgentHttp = "http://127.0.0.1:7878",
    [string]$ConversationId = "",
    [string]$RoundLabel = "round",
    [int]$TimeoutSeconds = 180,
    [int]$PollIntervalMs = 200,
    [switch]$NoStopAfterSlice,
    [string]$ArtifactDir = ""
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

# M2 experience prompt (same text as run12/13 and the 2026-10-15 sessions):
# loaded from asg1_prompt_codes.txt (hex code points, comma separated) written
# by the launcher; a static fallback copy lives below (ASCII-safe source).
function Fail {
    param([string]$Message)
    Write-Host ("FAIL: " + $Message) -ForegroundColor Red
    exit 1
}

$repoRoot = if ($PSScriptRoot) { Split-Path -Parent $PSScriptRoot } else { (Get-Location).Path }
if ([string]::IsNullOrWhiteSpace($ConversationId)) {
    $ConversationId = "asg1_" + (Get-Date -Format "yyyyMMdd_HHmmss")
}
if ([string]::IsNullOrWhiteSpace($ArtifactDir)) {
    $ArtifactDir = Join-Path $repoRoot ("artifacts\asg1_forensics\" + $RoundLabel + "_" + (Get-Date -Format "yyyyMMdd_HHmmss"))
}
New-Item -ItemType Directory -Force -Path $ArtifactDir | Out-Null

# Build the message from code points (ASCII-safe source).
$codePoints = @(
    0x6709,0x51E0,0x8F68,0x542C,0x8D77,0x6765,0x6BD4,0x8F83,0x5E72,0xFF0C,0x60F3,0x7ED9,0x5176,0x4E2D,0x4E00,0x6761,
    0x5408,0x9002,0x7684,0x8F68,0x52A0,0x4E00,0x70B9,0x6DF7,0x54CD,0xFF08,0x8870,0x51CF,0x77ED,0x4E9B,0xFF09,0xFF0C,
    0x4E0D,0x8981,0x7528,0x6574,0x4F53,0x589E,0x76CA,0x6216,0x20,0x45,0x51,0x20,0x6765,0x89E3,0x51B3,0x3002,
    0x8BF7,0x5148,0x89C2,0x5BDF,0x5DE5,0x7A0B,0xFF0C,0x518D,0x7ED9,0x4E00,0x4E2A,0x6709,0x754C,0x7684,0x5C0F,0x6B65,
    0x6539,0x8FDB,0x5EFA,0x8BAE,0x3002
)
# NOTE: the authoritative code points are regenerated by the launcher (python)
# into asg1_prompt_codes.txt next to this script when they differ; this static
# copy exists only so the script stays runnable standalone.

$sb = New-Object System.Text.StringBuilder
foreach ($cp in $codePoints) { [void]$sb.Append([char][int]$cp) }
$Message = $sb.ToString()

$codesFile = Join-Path $PSScriptRoot "asg1_prompt_codes.txt"
if (Test-Path -LiteralPath $codesFile) {
    $codesText = (Get-Content -LiteralPath $codesFile -Raw).Trim()
    if ($codesText.Length -gt 0) {
        $cpList = @($codesText -split ',' | ForEach-Object { [Convert]::ToInt32($_.Trim(), 16) })
        $sb2 = New-Object System.Text.StringBuilder
        foreach ($cp in $cpList) { [void]$sb2.Append([char]$cp) }
        $Message = $sb2.ToString()
    }
}

$base = $AgentHttp.TrimEnd("/")
$uri = [uri]$base
$hostName = $uri.Host
$port = $uri.Port

Write-Host "== ASG1 ask->slice gap forensics probe"
Write-Host ("round: " + $RoundLabel + "  conversation: " + $ConversationId)
Write-Host ("agent http: " + $base)
Write-Host ("message_len: " + $Message.Length)

try {
    $null = Invoke-RestMethod -Method GET -Uri ($base + "/agent/runtime/status") -TimeoutSec 10
} catch {
    Fail ("agent /agent/runtime/status unreachable: " + $_.Exception.Message)
}

$eventsUri = $base + "/agent/events?conversation_id=" + [uri]::EscapeDataString($ConversationId) + "&since=0&limit=200"
$stateUri = $base + "/agent/state"
[void](Invoke-RestMethod -Method GET -Uri $eventsUri -TimeoutSec 10)

$timeline = New-Object System.Collections.Generic.List[object]
function Add-Timeline {
    param([double]$TMs, [string]$Kind, [string]$Detail)
    $script:timeline.Add([pscustomobject]@{ t_ms = [math]::Round($TMs, 1); kind = $Kind; detail = $Detail })
}

# --- send the chat POST over raw TCP ---
$payload = @{
    conversation_id = $ConversationId
    message         = $Message
    context         = @{ agent_mode = "chat" }
} | ConvertTo-Json -Depth 6 -Compress
$bodyBytes = [System.Text.Encoding]::UTF8.GetBytes($payload)
$head = "POST /agent/chat HTTP/1.1" + [char]13 + [char]10 +
        "Host: " + $hostName + ":" + [string]$port + [char]13 + [char]10 +
        "Content-Type: application/json" + [char]13 + [char]10 +
        "Content-Length: " + [string]$bodyBytes.Length + [char]13 + [char]10 +
        "Connection: close" + [char]13 + [char]10 + [char]13 + [char]10
$headBytes = [System.Text.Encoding]::ASCII.GetBytes($head)

$tcp = New-Object System.Net.Sockets.TcpClient
try { $tcp.Connect($hostName, $port) } catch { Fail ("cannot connect agent TCP: " + $_.Exception.Message) }
$netStream = $tcp.GetStream()
$sw = [System.Diagnostics.Stopwatch]::StartNew()
$sentAt = (Get-Date).ToString("yyyy-MM-ddTHH:mm:ss.fffzzz")
try {
    $netStream.Write($headBytes, 0, $headBytes.Length)
    $netStream.Write($bodyBytes, 0, $bodyBytes.Length)
    $netStream.Flush()
} catch { Fail ("chat request write failed: " + $_.Exception.Message) }
Add-Timeline $sw.Elapsed.TotalMilliseconds "chat_post_sent" ("wall=" + $sentAt)
Write-Host ("sent_at=" + $sentAt)

$seenEventTypes = @{}
$lastStateSignature = ""
$sliceSeen = $false
$stopPosted = $false
$deadline = (Get-Date).AddSeconds($TimeoutSeconds)

while ((Get-Date) -lt $deadline) {
    # events face
    try {
        $body = Invoke-RestMethod -Method GET -Uri $eventsUri -TimeoutSec 10
        if ($body -and ($body.PSObject.Properties.Name -contains "events") -and $body.events) {
            foreach ($row in @($body.events)) {
                $et = [string]$row.type
                if (-not $seenEventTypes.ContainsKey($et)) {
                    $seenEventTypes[$et] = $true
                    Add-Timeline $sw.Elapsed.TotalMilliseconds "event_first_seen" ("type=" + $et + " created_at=" + [string]$row.created_at)
                }
            }
        }
    } catch { }
    # state face: /agent/state -> goal.task.run.{slices,turns}, goal.status
    try {
        $st = Invoke-RestMethod -Method GET -Uri $stateUri -TimeoutSec 10
        $sig = ""
        if ($st -and ($st.PSObject.Properties.Name -contains "goal") -and $st.goal) {
            $sig = "goal=" + [string]$st.goal.status
            $task = $st.goal.task
            if ($task) {
                $sig = $sig + ";task=" + [string]$task.status
                if (($task.PSObject.Properties.Name -contains "run") -and $task.run -and ($task.run.PSObject.Properties.Name -contains "slices") -and $task.run.slices) {
                    $firstSlice = @($task.run.slices)[0]
                    $sig = $sig + ";slice=" + [string]$firstSlice.status
                    if (-not $sliceSeen) {
                        $sliceSeen = $true
                        Add-Timeline $sw.Elapsed.TotalMilliseconds "slice_first_seen" ("slice_id=" + [string]$firstSlice.slice_id + " started_at=" + [string]$firstSlice.started_at + " seq=" + [string]$firstSlice.sequence)
                    }
                }
                if (($task.PSObject.Properties.Name -contains "run") -and $task.run -and ($task.run.PSObject.Properties.Name -contains "turns") -and $task.run.turns) {
                    $firstTurn = @($task.run.turns)[0]
                    $sig = $sig + ";turn=" + [string]$firstTurn.status
                }
            }
        }
        if ($sig -ne $lastStateSignature) {
            $lastStateSignature = $sig
            Add-Timeline $sw.Elapsed.TotalMilliseconds "state_change" $sig
        }
    } catch { }

    if ($sliceSeen -and -not $NoStopAfterSlice -and -not $stopPosted) {
        $stopPosted = $true
        $stopBody = @{ conversation_id = $ConversationId; reason = "user_stop" } | ConvertTo-Json -Compress
        try {
            $stopResp = Invoke-RestMethod -Method POST -Uri ($base + "/agent/turn/stop") -ContentType "application/json" -Body $stopBody -TimeoutSec 15
            Add-Timeline $sw.Elapsed.TotalMilliseconds "stop_posted" ("ok=" + [string]($stopResp -ne $null))
        } catch {
            Add-Timeline $sw.Elapsed.TotalMilliseconds "stop_posted" ("err=" + $_.Exception.Message)
        }
    }
    # end conditions: turn reached a terminal transport event after slice seen
    $terminalSeen = $false
    foreach ($et in $seenEventTypes.Keys) {
        if ($et -eq "turn.completed" -or $et -eq "turn.failed" -or $et -eq "turn.stopped") { $terminalSeen = $true }
    }
    if ($terminalSeen -and ($stopPosted -or $NoStopAfterSlice)) { break }
    if ($terminalSeen -and $sw.Elapsed.TotalSeconds -gt 10) { break }
    Start-Sleep -Milliseconds $PollIntervalMs
}

# drain the chat response
try {
    $buffer = New-Object byte[] 8192
    while ($netStream.Read($buffer, 0, $buffer.Length) -gt 0) { }
} catch { }
try { $tcp.Close() } catch { }

Start-Sleep -Milliseconds 500
$finalEvents = @()
try {
    $final = Invoke-RestMethod -Method GET -Uri $eventsUri -TimeoutSec 10
    if ($final -and ($final.PSObject.Properties.Name -contains "events") -and $final.events) { $finalEvents = @($final.events) }
} catch { }
$finalState = $null
try { $finalState = Invoke-RestMethod -Method GET -Uri $stateUri -TimeoutSec 10 } catch { }

$timelinePath = Join-Path $ArtifactDir "timeline.json"
$timeline | ConvertTo-Json -Depth 6 | Set-Content -Path $timelinePath -Encoding UTF8
$eventsPath = Join-Path $ArtifactDir "events_final.json"
$finalEvents | ConvertTo-Json -Depth 12 | Set-Content -Path $eventsPath -Encoding UTF8
$statePath = Join-Path $ArtifactDir "state_final.json"
if ($null -ne $finalState) { $finalState | ConvertTo-Json -Depth 12 | Set-Content -Path $statePath -Encoding UTF8 }

Write-Host ("timeline rows: " + [string]$timeline.Count)
foreach ($row in $timeline) {
    Write-Host ("  t+" + ("{0,9:F1}" -f [double]$row.t_ms) + "ms  " + $row.kind + "  " + $row.detail)
}
Write-Host ("artifact: " + $timelinePath)
if (-not $sliceSeen) {
    Write-Host ("WARN: slice_1 never observed within " + [string]$TimeoutSeconds + "s") -ForegroundColor Yellow
}
exit 0
